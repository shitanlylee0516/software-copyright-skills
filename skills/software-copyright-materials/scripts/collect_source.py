#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
collect_source.py

Review-only source code collector for Chinese software copyright material preparation.
Collects, validates, hashes, and organizes source code files strictly from an explicit manifest.
NOTE: The output generated by this tool is for internal review, auditing, and line counting only,
and DOES NOT constitute a final statutory copyright registration deposit document.
"""

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

# Sensitive file names or patterns that must NEVER be collected
SENSITIVE_EXACT_NAMES = {
    "credentials.json",
    "secrets.json",
    "id_rsa",
    "id_ed25519",
}

SENSITIVE_SUFFIXES = (
    ".key",
    ".pem",
    ".p12",
    ".pfx",
)

GLOB_CHARS = {"*", "?", "[", "]"}


def is_sensitive_component(comp: str) -> bool:
    """Checks if any path component (file or directory name) is sensitive."""
    c_lower = comp.lower().strip()
    if c_lower.startswith(".env"):
        return True
    if c_lower in SENSITIVE_EXACT_NAMES:
        return True
    if any(c_lower.endswith(suffix) for suffix in SENSITIVE_SUFFIXES):
        return True
    return False


def validate_manifest_path_format(rel_str: str) -> list[str]:
    """Validates path string format and returns normalized parts."""
    if not rel_str:
        raise ValueError("manifest path is empty")
    if ":" in rel_str:
        raise ValueError("colon ':' rejected")
    if "\\" in rel_str:
        raise ValueError("backslash '\\' rejected")
    if any(c in rel_str for c in GLOB_CHARS):
        raise ValueError("glob pattern rejected")
    if any(ord(c) < 32 or ord(c) == 127 for c in rel_str):
        raise ValueError("control character detected")
    if os.path.isabs(rel_str) or rel_str.startswith("/"):
        raise ValueError("absolute path rejected")

    parts = rel_str.split("/")
    if any(p == ".." or p == "." or p == "" for p in parts):
        raise ValueError("path traversal or empty component rejected")
    if any(p.lower() == ".git" for p in parts):
        raise ValueError("git directory rejected")

    for p in parts:
        if is_sensitive_component(p):
            raise ValueError(f"sensitive path component rejected: '{p}'")

    return parts


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Review-only source collector for software copyright preparation."
    )
    parser.add_argument("--root", required=True, help="Root directory containing source files.")
    parser.add_argument("--manifest", required=True, help="JSON manifest file with exact file list.")
    parser.add_argument("--out", required=True, help="Output directory path (must not exist beforehand).")
    args = parser.parse_args()

    root_path = Path(args.root).resolve()
    out_path = Path(args.out)
    manifest_path = Path(args.manifest)

    # 1. Output directory must not already exist
    if out_path.exists():
        sys.stderr.write("Error: Output path already exists. Refusing to overwrite.\n")
        sys.exit(1)

    # 2. Manifest file must exist and be valid JSON
    if not manifest_path.is_file():
        sys.stderr.write("Error: Manifest file not found.\n")
        sys.exit(1)

    try:
        manifest_data = json.loads(manifest_path.read_text(encoding="utf-8-sig"))
    except Exception:
        sys.stderr.write("Error: Failed to read or parse manifest JSON.\n")
        sys.exit(1)

    # Manifest must only contain exact 'files' key
    if not isinstance(manifest_data, dict) or set(manifest_data.keys()) != {"files"}:
        sys.stderr.write("Error: Manifest must be a JSON object containing only the 'files' key.\n")
        sys.exit(1)

    file_list = manifest_data["files"]
    if not isinstance(file_list, list) or len(file_list) == 0:
        sys.stderr.write("Error: Manifest 'files' list cannot be empty.\n")
        sys.exit(1)

    # Check for duplicates while preserving explicit ordering
    seen_paths = set()
    for rel_item in file_list:
        if not isinstance(rel_item, str):
            sys.stderr.write("Error: All items in 'files' must be strings.\n")
            sys.exit(1)
        if rel_item in seen_paths:
            sys.stderr.write("Error: Duplicate path in manifest.\n")
            sys.exit(1)
        seen_paths.add(rel_item)

    # 3. Pre-validate ALL inputs BEFORE creating the output directory
    validated_files = []
    total_physical_lines = 0

    for idx, rel_path_str in enumerate(file_list, start=1):
        try:
            # Check format rules
            parts = validate_manifest_path_format(rel_path_str)

            # Check each intermediate path component for symlinks / junctions / aliases
            curr = root_path
            for part in parts:
                curr = curr / part
                if curr.is_symlink():
                    raise ValueError("symlink detected in path component")
                # On Windows, check for junctions / reparse points / component aliases
                try:
                    if curr.exists():
                        if os.path.islink(curr) or curr.resolve() != curr.absolute():
                            raise ValueError("link/junction detected in path component")
                except OSError:
                    raise ValueError("filesystem error in path component")

            file_path = curr

            # Check if file exists and is a regular file
            if not file_path.exists():
                raise ValueError("file not found")
            if not file_path.is_file():
                raise ValueError("path is not a regular file")

            # Check resolved containment within root_path
            resolved_file = file_path.resolve()
            try:
                resolved_file.relative_to(root_path)
            except ValueError:
                raise ValueError("path resolves outside root directory")

            # Read exact raw bytes
            raw_bytes = file_path.read_bytes()

            # Verify UTF-8 encoding and absence of NUL bytes
            if b"\x00" in raw_bytes:
                raise ValueError("null bytes detected in text file")
            try:
                raw_bytes.decode("utf-8")
            except UnicodeDecodeError:
                raise ValueError("file is not valid UTF-8")

            # Compute line count and metadata
            line_count = len(raw_bytes.splitlines())
            total_physical_lines += line_count
            sha256_hex = hashlib.sha256(raw_bytes).hexdigest()

            validated_files.append({
                "rel_path": rel_path_str,
                "data": raw_bytes,
                "sha256": sha256_hex,
                "bytes": len(raw_bytes),
                "physical_lines": line_count,
            })
        except Exception:
            # Generic fixed error message with item index only; never echo exception string, root_path, or absolute paths
            sys.stderr.write(f"Validation error at item {idx}\n")
            sys.exit(1)

    # 4. All inputs validated cleanly: now create output directory
    try:
        out_path.mkdir(parents=True)
        files_dir = out_path / "files"
        files_dir.mkdir()
    except Exception:
        sys.stderr.write("Error: Failed to create output directory.\n")
        sys.exit(1)

    # 5. Write exact copies and build inventory & merged review file
    inventory_records = []
    merged_chunks = []

    try:
        for idx, item in enumerate(validated_files, start=1):
            rel_path = item["rel_path"]
            raw_bytes = item["data"]
            base_name = Path(rel_path).name
            copy_filename = f"{idx:04d}--{base_name}"
            copy_rel_path = f"files/{copy_filename}"

            # Write exact byte copy
            (files_dir / copy_filename).write_bytes(raw_bytes)

            inventory_records.append({
                "path": rel_path,
                "copy": copy_rel_path,
                "sha256": item["sha256"],
                "bytes": item["bytes"],
                "physical_lines": item["physical_lines"],
            })

            # Append to merged review
            header = f"=== FILE {idx:04d}: {rel_path} (bytes: {item['bytes']}, lines: {item['physical_lines']}) ===\n"
            footer = f"\n=== END FILE {idx:04d} ===\n\n"
            merged_chunks.append(header.encode("utf-8") + raw_bytes + footer.encode("utf-8"))

        # Write inventory.json
        inventory = {
            "review_only": True,
            "selected_file_count": len(inventory_records),
            "selected_physical_lines": total_physical_lines,
            "selected_files": inventory_records,
        }
        (out_path / "inventory.json").write_text(
            json.dumps(inventory, ensure_ascii=False, indent=2),
            encoding="utf-8"
        )

        # Write merged-review.txt
        (out_path / "merged-review.txt").write_bytes(b"".join(merged_chunks))
    except Exception:
        sys.stderr.write("Error: Failed to write output files.\n")
        sys.exit(1)


if __name__ == "__main__":
    main()
